"""Generate the Lean-file appendix and the inline part lists for main.tex.

Reads ../lean/closure.txt, ../lean/reports/depmap.tsv and groups.py. Each module
is assigned to the first matching group (the S11 list first), as in
check_coverage.py. Writes appendix.tex (one row per group) and steps.tex
(one macro \\leanstepS<k> per proof step, holding its parts as compact ranges).
"""
import fnmatch
import re
from pathlib import Path

import groups as G

here = Path(__file__).resolve().parent
closure = [l.strip() for l in (here / '../lean/closure.txt').read_text().splitlines() if l.strip()]
used = {l.split('\t')[0] for l in (here / '../lean/reports/depmap.tsv').read_text().splitlines() if l.strip()}


def assign(module):
    if any(fnmatch.fnmatchcase(module, p) for p in G.UNUSED_PATTERNS):
        return 'G00-unused'
    for g in G.GROUPS:
        if any(fnmatch.fnmatchcase(module, p) for p in g['patterns']):
            return g['id']
    return None


owner = {m: assign(m) for m in closure}
missing = [m for m, g in owner.items() if g is None]
if missing:
    raise SystemExit(f'unassigned modules: {missing[:5]} ... ({len(missing)})')

groups = list(G.GROUPS)
if not any(g['id'] == 'G00-unused' for g in groups):
    groups = [dict(id='G00-unused', step='S11', description=G.STEPS['S11'] + '.',
                   patterns=G.UNUSED_PATTERNS)] + groups


def part_number(module):
    x = re.match(r'BstLean\.Part(\d+)', module)
    return int(x.group(1)) if x else None


def ranges(nums):
    nums = sorted(set(nums))
    out, i = [], 0
    while i < len(nums):
        j = i
        while j + 1 < len(nums) and nums[j + 1] == nums[j] + 1:
            j += 1
        out.append(str(nums[i]) if i == j else f'{nums[i]}--{nums[j]}')
        i = j + 1
    return ', '.join(out)


def other_modules(mods):
    return sorted(m.split('.', 1)[1] for m in mods if part_number(m) is None)


def tex(s):
    """Escape text for LaTeX, leaving $...$ math segments unchanged."""
    parts = s.split('$')
    for i in range(0, len(parts), 2):
        t = re.sub(r'(\d) (\d{3})(?!\d)', r'\1{,}\2', parts[i])
        parts[i] = (t.replace('\\', r'\textbackslash{}').replace('_', r'\_').replace('&', r'\&')
                    .replace('%', r'\%').replace('#', r'\#').replace('≥', r'$\ge$').replace('–', '--'))
    return '$'.join(parts)


rows = []
for g in groups:
    mods = [m for m in closure if owner[m] == g['id']]
    nums = [part_number(m) for m in mods if part_number(m) is not None]
    where = ranges(nums)
    extra = other_modules(mods)
    if extra:
        where = (where + ', ' if where else '') + ', '.join(extra)
    rows.append((g['step'], g['id'], where, len(mods), sum(m in used for m in mods), g['description']))

lines = [r'\begin{longtable}{@{}l l p{0.30\textwidth} r r p{0.34\textwidth}@{}}',
         r'\toprule Step & Group & Parts & Files & Used & Role \\ \midrule \endhead']
for step, gid, where, n, u, desc in rows:
    lines.append(f'{step} & {tex(gid.split("-")[0])} & \\raggedright {tex(where)} & {n} & {u} & '
                 f'\\raggedright {tex(desc)} \\tabularnewline')
lines += [r'\midrule', f'& Total & & {len(closure)} & {len(used & set(closure))} & \\\\',
          r'\bottomrule', r'\end{longtable}']
(here / 'appendix.tex').write_text('\n'.join(lines) + '\n')

step_parts = {}
for m in closure:
    gid = owner[m]
    step = next(g['step'] for g in groups if g['id'] == gid)
    step_parts.setdefault(step, []).append(m)
macros = []
for step, mods in sorted(step_parts.items(), key=lambda kv: int(kv[0][1:])):
    nums = [part_number(m) for m in mods if part_number(m) is not None]
    extra = other_modules(mods)
    text = 'Parts ' + ranges(nums) + ('; ' + ', '.join(extra) if extra else '')
    macros.append(f'\\newcommand{{\\leanstep{chr(ord("A") + int(step[1:]))}}}{{{tex(text)}}}')
    print(f'{step}: {len(mods)} files; {text[:140]}')
(here / 'steps.tex').write_text('% generated by gen_appendix.py; \\leanstepA is S0, \\leanstepB is S1, ...\n'
                                + '\n'.join(macros) + '\n')
print(f'appendix rows: {len(rows)}; modules: {len(closure)}; used: {len(used & set(closure))}')
