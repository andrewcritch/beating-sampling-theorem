def modules(*suffixes):
    """Expand module-name patterns relative to BstLean."""
    return tuple("BstLean." + suffix for suffix in suffixes)


def parts(*numbers):
    """Match a numbered part without matching a longer part number."""
    return modules(*(f"Part{n}[!0-9]*" for n in numbers))


def group(identifier, step, description, patterns, evidence):
    return dict(id=identifier, step=step, description=description,
                patterns=tuple(patterns), evidence=evidence)


